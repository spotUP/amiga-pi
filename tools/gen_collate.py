#!/usr/bin/env python3
"""Generate amiga-pi/collate_tab.h: the order pi's ls sorts names in
(ls.ts: a.toLowerCase().localeCompare(b.toLowerCase()), ICU's collation),
for the Latin-1 range, as node 24's ICU gives it for English:

  co_pri   the primary (base letter) weight of each lowercased character,
           0 for one ICU ignores (soft hyphen)
  co_sec   its place among the characters of the same primary weight
           (accents), for the tie-break
  æ and ß expand to two letters (ae, ss) as ICU does at the base level.

    python3 -I tools/gen_collate.py        (needs node)
"""
import json, os, subprocess

JS = r'''
const L = 'en';
const cs = [];
for (let c = 0x20; c < 0x100; c++) {
  if (c >= 0x7f && c < 0xa0) continue;
  const s = String.fromCharCode(c).toLowerCase();
  if (s.length === 1) cs.push([c, s]);
}
const u = [...new Set(cs.map(x => x[1]))];
const base = (a, b) => a.localeCompare(b, L, {sensitivity: 'base'});
const full = (a, b) => a.localeCompare(b, L);
const ub = [...u].sort(base);
const pri = {}; let r = 1;
for (let i = 0; i < ub.length; i++) { if (i && base(ub[i], ub[i - 1]) !== 0) r++; pri[ub[i]] = base(ub[i], '') === 0 ? 0 : r; }
const uf = [...u].sort(full);
const sec = {}; uf.forEach((s, i) => sec[s] = i + 1);
const out = [];
for (const [c, s] of cs) out.push([c, pri[s], sec[s], s.charCodeAt(0)]);
console.log(JSON.stringify(out));
'''

def main():
    rows = json.loads(subprocess.run(['node', '-e', JS], stdout=subprocess.PIPE, check=True).stdout)
    pri = [0] * 256
    sec = [0] * 256
    for c, p, s, low in rows:
        pri[c] = p
        sec[c] = s
    # lowercase of the ASCII and Latin-1 capitals
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'amiga-pi', 'collate_tab.h')
    with open(out, 'w') as f:
        f.write('/* Generated by tools/gen_collate.py (node 24, ICU, English). Do not edit. */\n')
        for name, t in (('co_pri', pri), ('co_sec', sec)):
            f.write('static const unsigned char %s[256] = {\n' % name)
            for i in range(0, 256, 16):
                f.write('    ' + ', '.join('%d' % v for v in t[i:i + 16]) + ',\n')
            f.write('};\n')

if __name__ == '__main__':
    main()
