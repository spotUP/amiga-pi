// Generates amiga-pi/lower_tab.h: String.prototype.toLowerCase (what pi-tui's fuzzy.ts applies to the query and the text) for
// fuzzy.c, from node's own ICU: the one-to-one mappings as runs (first, last, delta, step), U+0130 (the one two-unit result),
// and the Cased / Case_Ignorable sets of the Final_Sigma rule (U+03A3 becomes U+03C2 at the end of a word, else U+03C3).
//   node tools/pi_oracle/gen_lower.mjs
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const maps = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const l = String.fromCodePoint(cp).toLowerCase();
  const pts = [...l];
  if (pts.length === 1 && pts[0].codePointAt(0) !== cp && cp !== 0x3a3) maps.push([cp, pts[0].codePointAt(0)]);
}
const runs = [];
for (const [cp, to] of maps) {
  const d = to - cp, r = runs[runs.length - 1];
  if (r && r.d === d && cp - r.last === r.step) { r.last = cp; continue; }
  if (r && r.d === d && r.first === r.last && cp - r.last <= 2) { r.step = cp - r.last; r.last = cp; continue; }
  runs.push({ first: cp, last: cp, d, step: 1 });
}
function ranges(re) {
  const out = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    if (re.test(String.fromCodePoint(cp))) {
      const r = out[out.length - 1];
      if (r && r[1] === cp - 1) r[1] = cp; else out.push([cp, cp]);
    }
  }
  return out;
}
const cased = ranges(/^\p{Cased}$/u), ign = ranges(/^\p{Case_Ignorable}$/u);
let s = "/* Generated by tools/pi_oracle/gen_lower.mjs (node " + process.version + ", ICU " + process.versions.icu + "). Do not edit. */\n";
s += "typedef struct { unsigned long first, last; long delta; unsigned char step; } lw_run;\n";
s += "static const lw_run lw_runs[] = {\n" + runs.map((r) => `    { 0x${r.first.toString(16)}, 0x${r.last.toString(16)}, ${r.d}, ${r.step} },`).join("\n") + "\n};\n";
s += "typedef struct { unsigned long first, last; } lw_range;\n";
s += "static const lw_range lw_cased[] = {\n" + cased.map((r) => `    { 0x${r[0].toString(16)}, 0x${r[1].toString(16)} },`).join("\n") + "\n};\n";
s += "static const lw_range lw_ignorable[] = {\n" + ign.map((r) => `    { 0x${r[0].toString(16)}, 0x${r[1].toString(16)} },`).join("\n") + "\n};\n";
writeFileSync(join(here, "../../amiga-pi/lower_tab.h"), s);
console.log("[OK] lower_tab.h runs " + runs.length + " cased " + cased.length + " ignorable " + ign.length);
