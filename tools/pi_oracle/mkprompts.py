#!/usr/bin/env python3
"""Writes amiga-pi/cp_prompts.[ch]: pi's summarization prompts (pi f10993bc core/compaction/ (compaction, utils, branch-summarization)) as C strings,
cut out of the template literals byte for byte so no one retypes them.
  mkprompts.py <oracle dir>   (default build/pi-oracle/oracle)"""
import os, re, sys
root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "build", "pi-oracle", "oracle")
want = [("compaction.ts", "SUMMARIZATION_PROMPT"), ("compaction.ts", "UPDATE_SUMMARIZATION_INSTRUCTIONS"),
        ("compaction.ts", "TURN_PREFIX_SUMMARIZATION_PROMPT"), ("utils.ts", "SUMMARIZATION_SYSTEM_PROMPT"),
        ("branch-summarization.ts", "BRANCH_SUMMARY_PREAMBLE"), ("branch-summarization.ts", "BRANCH_SUMMARY_PROMPT")]
def lit(path, name):
    s = open(os.path.join(root, "core", "compaction", path), encoding="utf-8").read()
    m = re.search(r"const %s = `" % name, s)
    a = m.end()
    b = s.index("`;", a)
    t = s[a:b]
    assert "${" not in t and "\\" not in t, name
    return t
def c(t):
    lines = t.split("\n")
    parts = []
    for i, l in enumerate(lines):
        l = l.replace("\\", "\\\\").replace('"', '\\"')
        parts.append('    "%s%s",' % (l, "\\n" if i < len(lines) - 1 else ""))
    return "\n".join(parts)
base = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "amiga-pi", "cp_prompts")
with open(base + ".c", "w", encoding="utf-8") as f, open(base + ".h", "w", encoding="utf-8") as h:
    note = "/* Generated by tools/pi_oracle/mkprompts.py from pi f10993bc core/compaction/ (compaction, utils, branch-summarization): do not edit.\n * Each prompt is an array of lines (a C89 string literal may be 509 characters), ended by 0. */\n"
    f.write(note + '#include "cp_prompts.h"\n\n')
    h.write(note + "#ifndef PI_CP_PROMPTS_H\n#define PI_CP_PROMPTS_H\n\n")
    for path, name in want:
        f.write("const char *const cp_%s[] = {\n%s\n    0\n};\n\n" % (name.lower(), c(lit(path, name))))
        h.write("extern const char *const cp_%s[];\n" % name.lower())
    h.write("\n#endif\n")
print("wrote", base)
