#!/usr/bin/env python3
"""Adds phase G's part of the pi oracle: pi f10993bc's own system prompt, context-file,
SYSTEM.md / APPEND_SYSTEM.md and project-trust code, so tools/pi_oracle/gen_resources.ts can
run it. Functions are cut out of pi's files by name (never retyped); only imports are
rewritten to the oracle's stubs.

  mkoracle_g.py [oracle dir]     (default ~/Code/amiga-pi/build/pi-oracle/oracle)

Fetches (once, into <oracle dir>/../g/) from pi f10993bc:
  core/system-prompt.ts   buildSystemPromptSections, renderProjectContext (as they are)
  core/trust-manager.ts   ProjectTrustStore, hasTrustRequiringProjectResources, getProjectTrustOptions
  core/resource-loader.ts loadContextFileFromDir, loadProjectContextFiles, resolvePromptInput,
                          discoverSystemPromptFile, discoverAppendSystemPromptFile (methods made functions
                          of cwd, agentDir, trusted)
  utils/paths.ts          canonicalizePath; utils/text.ts (stripBom)
Stubbed: findShadowedContextFile (git linked worktrees; there are none on the Amiga) returns
undefined; chalk; proper-lockfile (one process); config.ts (APP_NAME "pi", CONFIG_DIR_NAME ".pi",
docs paths); skills.ts formatSkillsForPrompt (no skills until phase I)."""
import os, re, sys, urllib.request

PI = "f10993bc7f28145df1375f3ff39c7f5c4cfc05f0"
oracle = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Code/amiga-pi/build/pi-oracle/oracle")
cache = os.path.join(os.path.dirname(os.path.abspath(oracle)), "g")
os.makedirs(cache, exist_ok=True)


def pi(path):
    local = os.path.join(cache, path.replace("/", "__"))
    if not os.path.exists(local):
        url = "https://raw." + "githubusercontent.com/earendil-works/pi/%s/%s" % (PI, path)
        open(local, "wb").write(urllib.request.urlopen(url).read())
    return open(local, encoding="utf-8").read()


def cut_function(src, name):
    m = re.search(r"^(export )?function %s\(" % re.escape(name), src, re.M)
    assert m, name
    end = src.index("\n}\n", m.start()) + 3
    return src[m.start():end]


def cut_method(src, name):
    m = re.search(r"^\tprivate %s\(\): string \| undefined \{\n" % re.escape(name), src, re.M)
    assert m, name
    end = src.index("\n\t}\n", m.end()) + 4
    body = src[m.end():end - 4]
    body = body.replace("this.cwd", "cwd").replace("this.agentDir", "agentDir")
    body = body.replace("this.settingsManager.isProjectTrusted()", "trusted")
    assert "this." not in body, name
    body = "\n".join(l[1:] if l.startswith("\t") else l for l in body.split("\n"))
    return "export function %s(cwd: string, agentDir: string, trusted: boolean): string | undefined {\n%s\n}\n" % (name, body)


def write(rel, text):
    p = os.path.join(oracle, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8").write(text)
    print("wrote", p)


src = "packages/coding-agent/src/"
head = "// generated by tools/pi_oracle/mkoracle_g.py from pi %s: do not edit\n" % PI[:8]

write("g/config.ts", head + 'export const APP_NAME = "pi";\nexport const CONFIG_DIR_NAME = ".pi";\n'
      'export function getReadmePath(): string { return "/pi/README.md"; }\n'
      'export function getDocsPath(): string { return "/pi/docs"; }\n'
      'export function getExamplesPath(): string { return "/pi/examples"; }\n')
write("g/stubs.ts", head + "export const chalk = { yellow: (s: string) => s };\n"
      "export default { lockSync: (_d: string, _o: unknown) => () => {} };\n"
      "export function formatSkillsForPrompt(_s: unknown[], _t: string): string { return \"\"; }\n"
      "export type Skill = unknown;\n")
paths = pi(src + "utils/paths.ts")
write("g/paths.ts", head + 'import { realpathSync } from "node:fs";\nexport { resolvePath } from "../utils/paths.ts";\n'
      + cut_function(paths, "canonicalizePath"))
write("g/text.ts", head + pi(src + "utils/text.ts"))

sp = pi(src + "core/system-prompt.ts")
sp = sp.replace('from "@earendil-works/pi-ai"', 'from "../ai/text.ts"')
sp = sp.replace('from "../config.ts"', 'from "./config.ts"')
sp = sp.replace('import { formatSkillsForPrompt, type Skill } from "./skills.ts";',
                'import { formatSkillsForPrompt, type Skill } from "./stubs.ts";')
write("g/system-prompt.ts", head + sp)

tm = pi(src + "core/trust-manager.ts")
tm = tm.replace('import lockfile from "proper-lockfile";', 'import lockfile from "./stubs.ts";')
tm = tm.replace('from "../config.ts"', 'from "./config.ts"')
tm = tm.replace('from "../utils/paths.ts"', 'from "./paths.ts"').replace('from "../utils/text.ts"', 'from "./text.ts"')
write("g/trust-manager.ts", head + tm)

rl = pi(src + "core/resource-loader.ts")
parts = [head,
         'import { existsSync, readFileSync, statSync } from "node:fs";\n',
         'import { basename, dirname, join, resolve, sep } from "node:path";\n',
         'import { chalk } from "./stubs.ts";\n',
         'import { CONFIG_DIR_NAME } from "./config.ts";\n',
         'import { canonicalizePath, resolvePath } from "./paths.ts";\n',
         'import { stripBom } from "./text.ts";\n',
         "// stub: git linked worktrees (findGitPaths) do not exist on the Amiga\n",
         "function findShadowedContextFile(_cwd: string): string | undefined { return undefined; }\n\n",
         "export " + cut_function(rl, "resolvePromptInput"), "\n",
         "export " + cut_function(rl, "loadContextFileFromDir"), "\n",
         cut_function(rl, "loadProjectContextFiles"), "\n",
         cut_method(rl, "discoverSystemPromptFile"), "\n",
         cut_method(rl, "discoverAppendSystemPromptFile")]
write("g/resources.ts", "".join(parts))
